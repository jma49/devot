import { existsSync, readFileSync } from 'node:fs'
import { expect, it } from 'vitest'
import { listFiles } from '../support/git-files'

const PHONE = 'src/renderer/src/phone'

const read = (path: string) => readFileSync(path, 'utf8')

const pageSources = () =>
  listFiles('.', 'src/renderer/src').filter(
    (path) => /\.tsx?$/.test(path) && !/\.test\.tsx?$/.test(path) && existsSync(path),
  )

it('draws no web find bar, formatting bar, bottom bar or Note Info sheet on the iPhone', () => {
  expect(existsSync(`${PHONE}/PhoneFindBar.tsx`)).toBe(false)
  expect(existsSync(`${PHONE}/useKeyboard.ts`)).toBe(false)
  const importers = pageSources().filter((path) =>
    /from '\.{1,2}\/(phone\/)?(PhoneFindBar|useKeyboard)'/.test(read(path)),
  )
  expect(importers).toStrictEqual([])
  const note = read(`${PHONE}/PhoneNote.tsx`)
  for (const part of [
    'function InfoSheet',
    'phone-note-bottom',
    'phone-accessory',
    'phone.info.',
  ]) {
    expect(note).not.toContain(part)
  }
  const css = read(`${PHONE}/phone.css`)
  for (const rule of [
    '.phone-note-bottom',
    '.phone-accessory',
    '.phone-find',
    '.phone-info-stat',
  ]) {
    expect(css).not.toContain(rule)
  }
})

it('plays the page’s haptics through Swift alone, with no Rust command for them', () => {
  const callers = pageSources().filter((path) => /invoke\(\s*'haptic'/.test(read(path)))
  expect(callers).toStrictEqual([])
  expect(read('src-tauri/build_commands.rs')).not.toMatch(/"haptic"/)
  expect(read('src-tauri/src/lib.rs')).not.toMatch(/native::haptic\b/)
  expect(read('src-tauri/capabilities/main.json')).not.toContain('allow-haptic')
  expect(existsSync('src-tauri/permissions/autogenerated/haptic.toml')).toBe(false)
  expect(read('src-tauri/src/native/ios/uikit.rs')).not.toMatch(/FeedbackGenerator/)
})

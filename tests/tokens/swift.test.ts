import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { flatten, resolve, type TokenTree } from '../../scripts/tokens/compile'
import { compileSwift, SWIFT_TOKENS, swiftName } from '../../scripts/tokens/swift'
import { BUILT_IN_THEMES } from '../../scripts/tokens/themes'
import { THEMES } from '../../src/core/editorSettings'

const read = (path: string) => JSON.parse(readFileSync(path, 'utf8')) as TokenTree
const base = read('design/tokens/base.tokens.json')
const light = read('design/tokens/themes/system.light.tokens.json')
const dark = read('design/tokens/themes/system.dark.tokens.json')
const themes = BUILT_IN_THEMES.map(({ id }) => ({
  id,
  light: read(`design/tokens/themes/${id}.light.tokens.json`),
  dark: read(`design/tokens/themes/${id}.dark.tokens.json`),
}))
const backdrops = read('design/tokens/backdrops.tokens.json')
const phoneThemes = read('design/tokens/phone-themes.tokens.json')
const swift = compileSwift(base, light, dark, themes, backdrops, phoneThemes)

const baseFlat = flatten(base)
const colours = (tree: TokenTree) =>
  resolve(flatten(tree), baseFlat).filter((token) => token.type === 'color')

/** The text of `public enum <name> {` up to its closing brace at the same indent. */
function block(source: string, opening: string): string {
  const start = source.indexOf(opening)
  if (start < 0) throw new Error(`no ${opening}`)
  const indent = /^ */.exec(source.slice(source.lastIndexOf('\n', start) + 1))![0]
  const end = source.indexOf(`\n${indent}}`, start)
  return source.slice(start, end + 1)
}

describe('the Swift tokens', () => {
  it('are the committed Tokens.swift', () => {
    expect(readFileSync(SWIFT_TOKENS, 'utf8')).toBe(swift)
  })

  it('parse as Swift: balanced brackets and nothing JavaScript left in them', () => {
    expect(swift.startsWith('// Generated by scripts/tokens/build.ts')).toBe(true)
    expect(swift).toContain('\nimport UIKit\n')
    const code = swift.replace(/"(?:[^"\\]|\\.)*"/g, '""').replace(/\/\/.*$/gm, '')
    const stack: string[] = []
    const pairs: Record<string, string> = { ')': '(', ']': '[', '}': '{' }
    const unmatched = [...code].filter((char) => {
      if ('([{'.includes(char)) stack.push(char)
      return char in pairs && stack.pop() !== pairs[char]
    })
    expect(unmatched).toEqual([])
    expect(stack).toEqual([])
    expect(code).not.toMatch(/undefined|NaN|Infinity|\[object|\$\{/)
    for (const line of code.split('\n').filter((l) => /static let/.test(l))) {
      expect(line).toMatch(/^\s+public static let [`\w]+: [\w.[\]?]+ = \S.*$/)
    }
  })

  it('names every theme the settings offer', () => {
    const all = /public static let all: \[Theme\] = \[(.*)\]\n/.exec(swift)![1]!
    expect(all.split(', ')).toEqual(THEMES.map((id) => `.${id}`))
    for (const id of THEMES) expect(swift).toContain(`Theme(id: "${id}"`)
  })

  it.each([
    ['defaultLight', light],
    ['defaultDark', dark],
    ...themes.flatMap((theme) => [
      [`${theme.id}Light`, theme.light] as const,
      [`${theme.id}Dark`, theme.dark] as const,
    ]),
  ] as const)('gives the %s palette every theme colour', (palette, tree) => {
    const body = block(swift, `static func ${palette}(_ name: ColorName) -> RGBA {`)
    const expected = colours(tree)
    expect(expected.length).toBeGreaterThan(200)
    for (const token of expected) {
      const value = token.value as { hex: string; alpha?: number }
      const rgba = `RGBA(0x${value.hex.slice(1)}, ${value.alpha ?? 1})`
      expect(body).toContain(`case .${swiftName(token.path).member}: return ${rgba}`)
    }
    expect(body.match(/case \./g)).toHaveLength(expected.length)
  })

  it('gives the gradient themes the default palette under their own phone colours, and their backdrop', () => {
    expect(swift).toMatch(/Theme\(\s*id: "dawn", light: \.dawnLight, dark: \.dawnDark,/)
    expect(swift).toContain('Backdrop(angle: 160')
    const dawn = block(swift, 'static func dawnLight(_ name: ColorName) -> RGBA {')
    expect(dawn).toContain('case .phoneBackground: return RGBA(0xfcedf3, 1)')
    expect(dawn).toContain('case .phoneCard: return RGBA(0xffffff, 0.3)')
    expect(dawn).toContain('case .phoneGlassOpaque: return RGBA(0xfdf2f6, 1)')
    expect(dawn).toContain('case .accentFill: return RGBA(0xb83a68, 1)')
    expect(dawn).toContain('case .accentText: return RGBA(0x9a2b55, 1)')
    const defaults = block(swift, 'static func defaultLight(_ name: ColorName) -> RGBA {')
    const phoneText = /case \.phoneText: return .*/.exec(defaults)![0]
    expect(dawn).toContain(phoneText)
    expect(block(swift, 'static func emberDark(_ name: ColorName) -> RGBA {')).toContain(
      'case .phoneBackground: return RGBA(0x1d140c, 1)',
    )
  })

  it('gives the glow themes their glow, and the default none', () => {
    expect(swift).toMatch(
      /id: "dawn", [^\n]*glow: Glow\(light: \[RGBA\(0xf5c4d8, 0\.9\), RGBA\(0xfdeedc, 0\.9\)\]/,
    )
    expect(swift).toMatch(/id: "ivory", [^\n]*glow: Glow\(light: \[RGBA\(0xefe6d2, 0\.6\)/)
    expect(swift).toMatch(/id: "default", [^\n]*backdrop: nil, glow: nil\)/)
  })

  it('lets SwiftUI follow the theme in effect', () => {
    expect(swift).toContain('import Observation')
    expect(block(swift, '@MainActor @Observable public final class ThemeState {')).toContain(
      'public var theme: Theme = .default',
    )
    expect(swift).toContain('get { ThemeState.shared.theme }')
  })

  it('carries every size, radius, duration and curve under its group', () => {
    const shared = baseFlat.filter(
      (token) => token.type !== 'color' && !token.path.startsWith('motion.spring.'),
    )
    expect(shared.length).toBeGreaterThan(400)
    for (const token of shared) {
      const { group, member } = swiftName(token.path)
      expect(block(swift, `public enum ${group} {`)).toMatch(
        new RegExp(`public static let ${member.replaceAll('`', '\\`')}: `),
      )
    }
    const size = block(swift, 'public enum Size {')
    expect(size).toContain('public static let phoneTarget: CGFloat = 44\n')
    expect(size).toContain('public static let phoneGroupedPadX: CGFloat = 16\n')
    const duration = block(swift, 'public enum Duration {')
    expect(duration).toContain('public static let phoneToast: TimeInterval = 4\n')
    expect(duration).toContain('public static let phoneAdjust: TimeInterval = 0.12\n')
    expect(block(swift, 'public enum Easing {')).toContain(
      'public static let phoneEnter: CubicBezier = CubicBezier(0.33, 1, 0.68, 1)\n',
    )
    expect(block(swift, 'public enum Ratio {')).toContain(
      'public static let phoneToastDismiss: CGFloat = 0.25\n',
    )
    expect(block(swift, 'public enum Velocity {')).toContain(
      'public static let phoneToastFlick: CGFloat = 800\n',
    )
    expect(block(swift, 'public enum Shadow {')).toContain(
      'public static let phoneFloatRadius: CGFloat = 28\n',
    )
  })

  it('names every theme colour as a colour of the theme in effect', () => {
    const accessors = block(swift, 'public enum Color {')
    for (const token of colours(light)) {
      const { member } = swiftName(token.path)
      expect(accessors).toContain(
        `public static var ${member}: UIColor { Theme.current.color(.${member}) }`,
      )
    }
    expect(accessors).toContain('phoneFloatShadow')
  })

  it('gives every spring both forms, from the formulas', () => {
    const springs = block(swift, 'public enum Spring {')
    const forms = [
      ...springs.matchAll(
        /static let (\w+): SpringParameters = SpringParameters\(dampingRatio: ([\d.]+), response: ([\d.]+), mass: ([\d.]+), stiffness: ([\d.]+), damping: ([\d.]+)\)/g,
      ),
    ].map(([, name, z, r, m, k, c]) => ({ name, z: +z!, r: +r!, m: +m!, k: +k!, c: +c! }))
    const pairs = baseFlat.filter((t) => t.path.endsWith('-response')).length
    expect(forms).toHaveLength(pairs)
    for (const { z, r, m, k, c } of forms) {
      expect(Math.abs(k - m * ((2 * Math.PI) / r) ** 2)).toBeLessThan(0.1)
      expect(Math.abs(c - (m * 4 * Math.PI * z) / r)).toBeLessThan(0.1)
    }
    const named = (name: string) => forms.find((form) => form.name === name)!
    expect(named('bouncy')).toMatchObject({ z: 0.62, r: 0.42, m: 1 })
    expect(named('bouncy').k).toBeCloseTo(223.8, 1)
    expect(named('bouncy').c).toBeCloseTo(18.55, 1)
    expect(named('phoneSettle')).toMatchObject({ z: 0.855, r: 0.29, m: 0.7 })
    expect(Math.round(named('phoneSettle').k / 10) * 10).toBe(330)
    expect(Math.round(named('phoneSettle').c)).toBe(26)
  })
})

describe('Swift token names', () => {
  it.each([
    ['size.phone-grouped-pad-x', 'Size', 'phoneGroupedPadX'],
    ['motion.duration.quick', 'Duration', 'quick'],
    ['motion.spring.phone-settle', 'Spring', 'phoneSettle'],
    ['font.size.body', 'Font', 'sizeBody'],
    ['note.heading.glass.h1-size', 'Note', 'headingGlassH1Size'],
    ['color.phone.text-faint', 'Color', 'phoneTextFaint'],
    ['space.4', 'Space', 'space4'],
    ['size.default', 'Size', '`default`'],
  ])('names %s %s.%s', (path, group, member) => {
    expect(swiftName(path)).toEqual({ group, member })
  })

  it('refuses two tokens with the same Swift name', () => {
    const tree = {
      size: {
        $type: 'dimension',
        'row-gap': { $value: { value: 1, unit: 'px' } },
        row: { gap: { $value: { value: 2, unit: 'px' } } },
      },
    }
    expect(() => compileSwift(tree, {}, {})).toThrow(/E_TOKEN_SWIFT_NAME size.row.gap/)
  })

  it('refuses a theme or backdrop id that is no Swift name', () => {
    const palette = { color: { $type: 'color', ink: { $value: { hex: '#000000' } } } }
    const hyphenated = [{ id: 'solarized-dark', light: palette, dark: palette }]
    expect(() => compileSwift({}, palette, palette, hyphenated)).toThrow(
      /E_TOKEN_SWIFT_THEME solarized-dark/,
    )
    const gradient = { $type: 'gradient', $value: [] }
    const digitFirst = { backdrop: { '2sky': { light: gradient, dark: gradient } } }
    expect(() => compileSwift({}, palette, palette, [], digitFirst)).toThrow(
      /E_TOKEN_SWIFT_THEME 2sky/,
    )
  })

  it('refuses a spring without both its damping and its response', () => {
    const tree = { motion: { spring: { $type: 'number', 'odd-damping': { $value: 0.5 } } } }
    expect(() => compileSwift(tree, {}, {})).toThrow(/E_TOKEN_SWIFT_SPRING odd/)
  })
})

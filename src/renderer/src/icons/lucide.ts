/**
 * Lucide has no filled variants, so where SF Symbols fills a shape the icon is
 * filled with the current colour (`solid`) or washed with it (`tint`: the ring
 * and glyph stay in full colour over a light fill).
 */
export const LUCIDE_FILLS: Partial<Record<IconName, 'solid' | 'tint'>> = {
  'note.pinned': 'solid',
  tag: 'solid',
  'status.active': 'tint',
  'status.onHold': 'tint',
  'status.completed': 'tint',
  'status.dropped': 'tint',
}

const STROKES: Record<SymbolWeight, number> = {
  ultralight: 1.25,
  thin: 1.5,
  light: 1.75,
  regular: 2,
  medium: 2.25,
  semibold: 2.25,
  bold: 2.5,
  heavy: 2.5,
  black: 2.5,
}

/** Lucide has one stroke per icon; the SF weight picks its width so a thin toolbar stays thin. */
export const lucideStroke = (weight: SymbolWeight = 'regular'): number => STROKES[weight]

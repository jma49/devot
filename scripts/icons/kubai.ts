const exportName = (name: string) =>
  name
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')

/** The two generated files, from the catalog's Kubai names. */
export function render(catalog: { symbols: Record<string, string> }): { ts: string; css: string } {
  const icons = kubai as unknown as Record<string, { markup?: string } | undefined>
  const names = [...new Set(Object.values(catalog.symbols))].sort()
  const paints = new Map<string, string>()
  const glyphs = names.map((name) => {
    const markup = icons[exportName(name)]?.markup
    if (typeof markup !== 'string') throw new Error(`E_KUBAI_UNKNOWN_ICON ${name}`)
    if (/<script|\son\w+=|[^\x20-\x7e]/i.test(markup))
      throw new Error(`E_KUBAI_UNSAFE_MARKUP ${name}`)
    // The window's CSP refuses style attributes, so each paint becomes a class; the data attributes only drive Kubai's hover motion.
    const content = markup
      .replace(/ data-(?:n|under|over)="[^"]*"/g, '')
      .replace(/ style="([^"]*)"/g, (_, paint: string) => {
        if (!paints.has(paint)) paints.set(paint, `ki-p${paints.size}`)
        return ` class="${paints.get(paint)}"`
      })
    if (/ style=| class="(?!ki-p)/.test(content))
      throw new Error(`E_KUBAI_UNEXPECTED_ATTRIBUTE ${name}`)
    return `  ${JSON.stringify(name)}: ${JSON.stringify(content)},`
  })
  const ts = `${LICENSE}
// Generated by scripts/icons/kubai.ts from kubai-icons (pnpm icons:kubai); do not edit.
import './kubaiGlyphs.css'

/** Each glyph's SVG content on Kubai's canvas; \`__K__\` stands for the drawn instance's own id. */
export const KUBAI_GLYPHS: Readonly<Record<string, string>> = {
${glyphs.join('\n')}
}
`
  const css = `${LICENSE}
/* Generated by scripts/icons/kubai.ts from kubai-icons (pnpm icons:kubai); do not edit. */
${[...paints].map(([paint, name]) => `.${name} { ${paint}; }`).join('\n')}
`
  return { ts, css }
}

function main() {
  const { ts, css } = render(JSON.parse(readFileSync(CATALOG, 'utf8')))
  const files = [
    [GLYPHS_TS, ts],
    [GLYPHS_CSS, css],
  ] as const
  if (process.argv.includes('--check')) {
    const stale = files.filter(([path, text]) => {
      try {
        return readFileSync(path, 'utf8') !== text
      } catch {
        return true
      }
    })
    if (stale.length > 0) {
      console.error(
        `E_KUBAI_GLYPHS_STALE ${stale.map(([path]) => path).join(' ')}: run pnpm icons:kubai`,
      )
      process.exit(1)
    }
    return
  }
  for (const [path, text] of files) writeFileSync(path, text)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main()

// Compiles the design tokens into Tokens.swift for the iPhone's native screens; `build.ts` writes it.
import {
  BACKDROP_DEGREES,
  flatten,
  resolve,
  type ColorValue,
  type FlatToken,
  type ThemeTokens,
  type TokenTree,
} from './compile.ts'

export const SWIFT_TOKENS =
  'src-tauri/apple/DevotScreens/Sources/DevotScreens/Generated/Tokens.swift'

const HEADER = '// Generated by scripts/tokens/build.ts from design/tokens. Do not edit.'

const KEYWORDS = new Set(
  (
    'associatedtype as break case catch class continue default defer deinit do else enum extension ' +
    'fallthrough false fileprivate for func guard if import in init inout internal is let nil ' +
    'open operator private protocol public repeat rethrows return self Self static struct subscript ' +
    'super switch throw throws true try typealias var where while'
  ).split(' '),
)

export const escapeKeyword = (name: string) => (KEYWORDS.has(name) ? `\`${name}\`` : name)

/** `a-b_c` and `a.b-c` as `aBC`; a name that would start with a digit takes `prefix` first. */
export function camelCase(segments: readonly string[], prefix = ''): string {
  const words = segments.join('-').split(/[-_.]/).filter(Boolean)
  const joined = words
    .map((word, i) => (i === 0 ? word[0]!.toLowerCase() : word[0]!.toUpperCase()) + word.slice(1))
    .join('')
  return /^\d/.test(joined) ? `${prefix}${joined}` : joined
}

/** The enum a token sits in (a top-level group, or the kind of motion) and its name there. */
export function swiftName(path: string): { group: string; member: string } {
  const segments = path.split('.')
  const groupAt = segments[0] === 'motion' ? 1 : 0
  const group = segments[groupAt]!
  const member = camelCase(segments.slice(groupAt + 1), camelCase([group]))
  return {
    group: group[0]!.toUpperCase() + camelCase([group]).slice(1),
    member: escapeKeyword(member),
  }
}

const num = (n: number) => String(Math.round(n * 1e6) / 1e6)

function rgba(color: ColorValue, path: string): string {
  if (!/^#[0-9a-f]{6}$/i.test(color.hex)) throw new Error(`E_TOKEN_SWIFT_COLOR ${path}`)
  return `RGBA(0x${color.hex.slice(1).toLowerCase()}, ${num(color.alpha ?? 1)})`
}

interface SwiftConstant {
  member: string
  type: string
  value: string
}

function constant(token: FlatToken): Omit<SwiftConstant, 'member'> {
  switch (token.type) {
    case 'dimension': {
      const d = token.value as { value: number; unit: string }
      if (d.unit !== 'px') throw new Error(`E_TOKEN_SWIFT_UNIT ${token.path} ${d.unit}`)
      return { type: 'CGFloat', value: num(d.value) }
    }
    case 'number':
    case 'fontWeight':
      return { type: 'CGFloat', value: num(Number(token.value)) }
    case 'duration': {
      const d = token.value as { value: number; unit: 'ms' | 's' }
      return { type: 'TimeInterval', value: num(d.unit === 'ms' ? d.value / 1000 : d.value) }
    }
    case 'cubicBezier':
      return {
        type: 'CubicBezier',
        value: `CubicBezier(${(token.value as number[]).map(num).join(', ')})`,
      }
    case 'fontFamily': {
      const families = (Array.isArray(token.value) ? token.value : [token.value]).map(String)
      return { type: '[String]', value: `[${families.map((f) => JSON.stringify(f)).join(', ')}]` }
    }
    default:
      throw new Error(`E_TOKEN_TYPE_UNSUPPORTED ${token.path} ${token.type}`)
  }
}

const SPRING_PART = /^(.+)-(damping|response|mass)$/

/**
 * Each spring in both forms: its damping ratio and response, and mass, stiffness and damping,
 * with k = m (2π / response)² and c = m 4π ζ / response. Its mass is 1 unless a `-mass` token says.
 */
function springs(tokens: readonly FlatToken[]): FlatToken[] {
  const parts = new Map<string, Partial<Record<'damping' | 'response' | 'mass', number>>>()
  for (const token of tokens) {
    const name = token.path.slice('motion.spring.'.length)
    const match = SPRING_PART.exec(name)
    if (!match) throw new Error(`E_TOKEN_SWIFT_SPRING ${name}`)
    const part = match[2] as 'damping' | 'response' | 'mass'
    parts.set(match[1]!, { ...parts.get(match[1]!), [part]: Number(token.value) })
  }
  return [...parts].map(([name, { damping, response, mass = 1 }]) => {
    if (damping === undefined || response === undefined) {
      throw new Error(`E_TOKEN_SWIFT_SPRING ${name}`)
    }
    const stiffness = mass * ((2 * Math.PI) / response) ** 2
    const coefficient = (mass * 4 * Math.PI * damping) / response
    const round = (n: number) => num(Math.round(n * 100) / 100)
    return {
      path: `motion.spring.${name}`,
      type: 'spring',
      systemAccent: false,
      value:
        `SpringParameters(dampingRatio: ${num(damping)}, response: ${num(response)}, ` +
        `mass: ${num(mass)}, stiffness: ${round(stiffness)}, damping: ${round(coefficient)})`,
    }
  })
}

/** The enums of constants, in the order their groups first appear. */
function constantGroups(tokens: readonly FlatToken[]): Map<string, SwiftConstant[]> {
  const springTokens = tokens.filter((t) => t.path.startsWith('motion.spring.'))
  const firstSpring = tokens.indexOf(springTokens[0]!)
  const ordered = tokens.filter((t) => !springTokens.includes(t))
  if (springTokens.length > 0) ordered.splice(firstSpring, 0, ...springs(springTokens))
  const groups = new Map<string, SwiftConstant[]>()
  const seen = new Map<string, string>()
  for (const token of ordered) {
    const { group, member } = swiftName(token.path)
    const key = `${group}.${member}`
    if (seen.has(key)) throw new Error(`E_TOKEN_SWIFT_NAME ${token.path}`)
    seen.set(key, token.path)
    const entry =
      token.type === 'spring'
        ? { type: 'SpringParameters', value: String(token.value) }
        : constant(token)
    groups.set(group, [...(groups.get(group) ?? []), { member, ...entry }])
  }
  return groups
}

const TYPES = `  public struct RGBA: Sendable, Equatable {
    public let red: CGFloat
    public let green: CGFloat
    public let blue: CGFloat
    public let alpha: CGFloat

    init(_ hex: UInt32, _ alpha: CGFloat) {
      red = CGFloat((hex >> 16) & 0xff) / 255
      green = CGFloat((hex >> 8) & 0xff) / 255
      blue = CGFloat(hex & 0xff) / 255
      self.alpha = alpha
    }

    public var uiColor: UIColor { UIColor(red: red, green: green, blue: blue, alpha: alpha) }
  }

  public struct CubicBezier: Sendable, Equatable {
    public let x1: CGFloat
    public let y1: CGFloat
    public let x2: CGFloat
    public let y2: CGFloat

    init(_ x1: CGFloat, _ y1: CGFloat, _ x2: CGFloat, _ y2: CGFloat) {
      self.x1 = x1
      self.y1 = y1
      self.x2 = x2
      self.y2 = y2
    }

    @MainActor public var timingParameters: UICubicTimingParameters {
      UICubicTimingParameters(
        controlPoint1: CGPoint(x: x1, y: y1), controlPoint2: CGPoint(x: x2, y: y2))
    }
  }

  public struct SpringParameters: Sendable, Equatable {
    public let dampingRatio: CGFloat
    public let response: TimeInterval
    public let mass: CGFloat
    public let stiffness: CGFloat
    public let damping: CGFloat

    /// With \`response\`, the arguments of \`UIView.animate(springDuration:bounce:)\`.
    public var bounce: CGFloat { 1 - dampingRatio }

    /// The same spring for \`UIViewPropertyAnimator\`; it never clamps an overshoot.
    @MainActor public func timingParameters(initialVelocity: CGVector = .zero) -> UISpringTimingParameters {
      UISpringTimingParameters(
        mass: mass, stiffness: stiffness, damping: damping, initialVelocity: initialVelocity)
    }
  }

  public struct GradientStop: Sendable, Equatable {
    public let color: RGBA
    public let location: CGFloat
  }

  public struct Backdrop: Sendable, Equatable {
    /// Degrees clockwise from straight up, as CSS draws the gradient.
    public let angle: CGFloat
    public let light: [GradientStop]
    public let dark: [GradientStop]
  }
`

/**
 * Tokens.swift: every theme's colours as palettes the system resolves for light and dark, and the
 * non-colour base tokens as constants. A gradient theme in \`backdrops\` keeps the default palette.
 */
export function compileSwift(
  base: TokenTree,
  light: TokenTree,
  dark: TokenTree,
  themes: readonly ThemeTokens[] = [],
  backdrops: TokenTree = {},
): string {
  const baseFlat = flatten(base)
  const colours = (tree: TokenTree) =>
    resolve(flatten(tree), baseFlat).filter((t) => t.type === 'color')
  const palettes = [
    { name: 'defaultLight', tokens: colours(light) },
    { name: 'defaultDark', tokens: colours(dark) },
    ...themes.flatMap((theme) => [
      { name: `${theme.id}Light`, tokens: colours(theme.light) },
      { name: `${theme.id}Dark`, tokens: colours(theme.dark) },
    ]),
  ]
  const order = palettes[0]!.tokens.map((t) => t.path)
  const names = new Map<string, string>()
  for (const path of order) {
    const { member } = swiftName(path)
    if ([...names.values()].includes(member)) throw new Error(`E_TOKEN_SWIFT_NAME ${path}`)
    names.set(path, member)
  }
  for (const palette of palettes) {
    if (
      palette.tokens
        .map((t) => t.path)
        .sort()
        .join() !== [...order].sort().join()
    ) {
      throw new Error(`E_TOKEN_THEMES_DIFFER ${palette.name}`)
    }
  }

  const backdropThemes = [...new Set(flatten(backdrops).map((t) => t.path.split('.')[1]!))].map(
    (id) => {
      const stops = (appearance: 'light' | 'dark') => {
        const token = flatten(backdrops).find((t) => t.path === `backdrop.${id}.${appearance}`)
        if (token?.type !== 'gradient') throw new Error(`E_TOKEN_BACKDROP ${id} ${appearance}`)
        const list = (token.value as { color: ColorValue; position: number }[]).map(
          (stop) =>
            `GradientStop(color: ${rgba(stop.color, token.path)}, location: ${num(stop.position)})`,
        )
        return `[${list.join(', ')}]`
      }
      return {
        id,
        backdrop: `Backdrop(angle: ${BACKDROP_DEGREES}, light: ${stops('light')}, dark: ${stops('dark')})`,
      }
    },
  )
  const themeList = [
    { id: 'default', palette: 'default', backdrop: 'nil' },
    ...themes.map((theme) => ({ id: theme.id, palette: theme.id, backdrop: 'nil' })),
    ...backdropThemes.map((theme) => ({ ...theme, palette: 'default' })),
  ]

  const lines: string[] = [HEADER, '', 'import UIKit', '', 'public enum Tokens {', TYPES]

  lines.push('  public enum ColorName: String, CaseIterable, Sendable {')
  for (const path of order) lines.push(`    case ${names.get(path)} = "${path}"`)
  lines.push('  }', '')

  lines.push('  public enum Palette: Sendable {')
  lines.push(`    case ${palettes.map((p) => p.name).join(', ')}`, '')
  lines.push('    public func rgba(_ name: ColorName) -> RGBA {', '      switch self {')
  for (const { name } of palettes) lines.push(`      case .${name}: return Palettes.${name}(name)`)
  lines.push('      }', '    }', '  }', '')

  lines.push('  enum Palettes {')
  palettes.forEach((palette, i) => {
    if (i > 0) lines.push('')
    lines.push(
      `    static func ${palette.name}(_ name: ColorName) -> RGBA {`,
      '      switch name {',
    )
    const byPath = new Map(palette.tokens.map((t) => [t.path, t]))
    for (const path of order) {
      const value = rgba(byPath.get(path)!.value as ColorValue, path)
      lines.push(`      case .${names.get(path)}: return ${value}`)
    }
    lines.push('      }', '    }')
  })
  lines.push('  }', '')

  lines.push(
    '  public struct Theme: Sendable, Equatable {',
    '    public let id: String',
    '    public let light: Palette',
    '    public let dark: Palette',
    '    public let backdrop: Backdrop?',
    '',
    '    init(id: String, light: Palette, dark: Palette, backdrop: Backdrop?) {',
    '      self.id = id',
    '      self.light = light',
    '      self.dark = dark',
    '      self.backdrop = backdrop',
    '    }',
    '',
    '    /// The theme with the id the `theme` editor setting stores, if there is one.',
    '    public init?(_ id: String) {',
    '      guard let theme = Theme.all.first(where: { $0.id == id }) else { return nil }',
    '      self = theme',
    '    }',
    '',
    '    /// The theme `Tokens.Color` draws in.',
    '    @MainActor public static var current: Theme = .default',
    '',
    '    public func color(_ name: ColorName) -> UIColor {',
    '      let light = light.rgba(name)',
    '      let dark = dark.rgba(name)',
    '      return UIColor(dynamicProvider: { traits in',
    '        (traits.userInterfaceStyle == .dark ? dark : light).uiColor',
    '      })',
    '    }',
    '',
  )
  for (const theme of themeList) {
    lines.push(
      `    public static let ${escapeKeyword(theme.id)}: Theme = Theme(id: "${theme.id}", ` +
        `light: .${theme.palette}Light, dark: .${theme.palette}Dark, backdrop: ${theme.backdrop})`,
    )
  }
  lines.push(
    `    public static let all: [Theme] = [${themeList.map((t) => `.${t.id}`).join(', ')}]`,
    '  }',
    '',
  )

  lines.push('  @MainActor public enum Color {')
  for (const path of order) {
    const member = names.get(path)!
    lines.push(`    public static var ${member}: UIColor { Theme.current.color(.${member}) }`)
  }
  lines.push('  }')

  const shared = baseFlat.filter((t) => t.type !== 'color')
  for (const [group, constants] of constantGroups(shared)) {
    lines.push('', `  public enum ${group} {`)
    for (const c of constants) {
      lines.push(`    public static let ${c.member}: ${c.type} = ${c.value}`)
    }
    lines.push('  }')
  }
  lines.push('}', '')
  return lines.join('\n')
}

// Compiles DTCG design tokens into CSS custom properties and TS constants; `build.ts` does the file I/O.

export type TokenTree = { [key: string]: TokenTree | Token | unknown }

export interface Token {
  $value: unknown
  $type?: string
  $extensions?: { 'app.devot'?: { source?: string } }
}

export interface ColorValue {
  colorSpace: 'srgb'
  components: [number, number, number]
  hex: string
  alpha?: number
}

interface DimensionValue {
  value: number
  unit: 'px' | 'rem'
}

export interface FlatToken {
  path: string
  type: string
  value: unknown
  systemAccent: boolean
}

const isToken = (node: unknown): node is Token =>
  typeof node === 'object' && node !== null && '$value' in node

export function flatten(tree: TokenTree, prefix = '', inheritedType = ''): FlatToken[] {
  const out: FlatToken[] = []
  const groupType = typeof tree['$type'] === 'string' ? (tree['$type'] as string) : inheritedType
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$')) continue
    const path = prefix ? `${prefix}.${key}` : key
    if (isToken(node)) {
      out.push({
        path,
        type: node.$type ?? groupType,
        value: node.$value,
        systemAccent: node.$extensions?.['app.devot']?.source === 'system-accent',
      })
    } else if (typeof node === 'object' && node !== null) {
      out.push(...flatten(node as TokenTree, path, groupType))
    }
  }
  return out
}

const REFERENCE = /^\{([^}]+)\}$/

export function resolve(tokens: FlatToken[], base: FlatToken[]): FlatToken[] {
  const byPath = new Map([...base, ...tokens].map((t) => [t.path, t]))
  const resolveValue = (value: unknown, seen: Set<string>): unknown => {
    if (typeof value !== 'string') return value
    const match = REFERENCE.exec(value)
    if (!match) return value
    const target = byPath.get(match[1]!)
    if (!target) throw new Error(`E_TOKEN_REFERENCE_MISSING ${match[1]}`)
    if (seen.has(target.path)) throw new Error(`E_TOKEN_REFERENCE_CYCLE ${target.path}`)
    return resolveValue(target.value, new Set([...seen, target.path]))
  }
  return tokens.map((t) => ({ ...t, value: resolveValue(t.value, new Set([t.path])) }))
}

const round = (n: number) => Math.round(n * 1000) / 1000

function cssColor(c: ColorValue): string {
  if (c.alpha === undefined || c.alpha === 1) return c.hex
  const [r, g, b] = c.components.map((x) => Math.round(x * 255))
  return `rgb(${r} ${g} ${b} / ${round(c.alpha)})`
}

/** The direction of every backdrop gradient: top to bottom, leaning right. */
export const BACKDROP_DEGREES = 160

export function cssValue(token: FlatToken): string {
  switch (token.type) {
    case 'color':
      return cssColor(token.value as ColorValue)
    case 'gradient': {
      const stops = (token.value as { color: ColorValue; position: number }[]).map(
        (s) => `${cssColor(s.color)} ${round(s.position * 100)}%`,
      )
      return `linear-gradient(${BACKDROP_DEGREES}deg, ${stops.join(', ')})`
    }
    case 'dimension': {
      const d = token.value as DimensionValue
      return `${d.value}${d.unit}`
    }
    case 'fontFamily': {
      const families = Array.isArray(token.value) ? token.value : [token.value]
      return families
        .map((f) => (/^[a-z-]+$/i.test(String(f)) ? String(f) : `'${String(f)}'`))
        .join(', ')
    }
    case 'duration': {
      const d = token.value as { value: number; unit: 'ms' | 's' }
      return `${d.value}${d.unit}`
    }
    case 'cubicBezier':
      return `cubic-bezier(${(token.value as number[]).join(', ')})`
    case 'fontWeight':
    case 'number':
      return String(token.value)
    default:
      throw new Error(`E_TOKEN_TYPE_UNSUPPORTED ${token.path} ${token.type}`)
  }
}

export const cssVarName = (path: string) => `--${path.replaceAll('.', '-')}`

/**
 * System-accent colours read a runtime variable named after the token's role (`--system-accent-fill-light`
 * for `color.accent.fill`, set in theme/accent.ts) and fall back to the token's own value.
 */
function themeDeclaration(
  token: FlatToken,
  appearance: 'light' | 'dark',
  followsSystemAccent = true,
): string {
  const value = cssValue(token)
  const role = token.path.split('.').at(-1)
  const css =
    token.systemAccent && followsSystemAccent
      ? `var(--system-accent-${role}-${appearance}, ${value})`
      : value
  return `  ${cssVarName(token.path)}: ${css};`
}

export interface CompiledTokens {
  css: string
  ts: string
}

const HEADER = 'Generated by scripts/tokens/build.ts from design/tokens. Do not edit.'

export const DARK_QUERY = '(prefers-color-scheme: dark)'

/** Follows the system unless Settings > Appearance chose one (`data-appearance`, theme/appearance.ts). */
const FOLLOWS_SYSTEM = ":root:not([data-appearance='light'])"

/** The root when Settings chose an appearance, or any element pinned to one (`data-appearance-preview`, the theme cards). */
const CHOSEN = (appearance: 'light' | 'dark') =>
  `:root[data-appearance='${appearance}'], [data-appearance-preview='${appearance}']`

export interface ThemeTokens {
  /** The `data-theme` value on the root (a plain lowercase word). */
  id: string
  light: TokenTree
  dark: TokenTree
}

const THEME_ID = /^[a-z][a-z0-9]*$/

/** The rules of a built-in theme, in the order that makes them win (see `compile`). */
function themeRules(id: string, lightDeclarations: string[], darkDeclarations: string[]): string[] {
  const root = `:root[data-theme='${id}']`
  // A theme's rules are one attribute heavier than the default theme's wherever both could apply,
  // and come after them, so the theme wins in every context. `data-theme-preview` shows the theme
  // in the appearance `data-appearance-preview` names (the Settings theme cards).
  const chosen = (appearance: 'light' | 'dark') =>
    `${root}[data-appearance='${appearance}'], [data-theme-preview='${id}'][data-appearance-preview='${appearance}']`
  return [
    `${root} {`,
    ...lightDeclarations,
    '}',
    '',
    `@media ${DARK_QUERY} {`,
    `  ${root}:not([data-appearance='light']) {`,
    ...darkDeclarations.map((d) => `  ${d}`),
    '  }',
    '}',
    '',
    `${chosen('dark')} {`,
    '  color-scheme: dark;',
    ...darkDeclarations,
    '}',
    '',
    `${chosen('light')} {`,
    '  color-scheme: light;',
    ...lightDeclarations,
    '}',
    '',
  ]
}

interface GradientStop {
  color: ColorValue
  position: number
}

function colourAt(stops: readonly GradientStop[], at: number): ColorValue {
  const exact = stops.find((s) => s.position === at)
  if (exact) return exact.color
  const next = stops.findIndex((s) => s.position > at)
  if (next <= 0) return stops.at(next === 0 ? 0 : -1)!.color
  const [a, b] = [stops[next - 1]!, stops[next]!]
  const share = (at - a.position) / (b.position - a.position)
  const mix = (x: number, y: number) => x + (y - x) * share
  const components = a.color.components.map((c, i) => mix(c, b.color.components[i]!)) as [
    number,
    number,
    number,
  ]
  const alpha = mix(a.color.alpha ?? 1, b.color.alpha ?? 1)
  const hex = `#${components
    .map((c) =>
      Math.round(c * 255)
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')}`
  return { colorSpace: 'srgb', components, hex, ...(alpha === 1 ? {} : { alpha }) }
}

/** Settings > Appearance > Gradient, 0 to 100; a page that never sets it shows the design. */
const GRADIENT_STRENGTH = 'calc(var(--gradient-strength, 100) * 1%)'

/** Every stop mixed towards the gradient's middle colour: 100 is the design, 0 that colour alone. */
function backdropGradient(token: FlatToken): string {
  const stops = token.value as GradientStop[]
  const solid = cssColor(colourAt(stops, 0.5))
  const mixed = stops.map((s) => {
    const colour = cssColor(s.color)
    const mix =
      colour === solid ? colour : `color-mix(in srgb, ${colour} ${GRADIENT_STRENGTH}, ${solid})`
    return `${mix} ${round(s.position * 100)}%`
  })
  return `linear-gradient(${BACKDROP_DEGREES}deg, ${mixed.join(', ')})`
}

/**
 * The gradient themes in `backdrops`: `backdrop.<id>.light|dark`, each a gradient. Such a theme
 * keeps the default theme's colours, accent included, and adds `--backdrop`.
 */
export function backdropThemes(
  backdrops: TokenTree,
): { id: string; light: string; dark: string }[] {
  const flat = flatten(backdrops)
  const ids = [...new Set(flat.map((t) => t.path.split('.')[1]!))]
  return ids.map((id) => {
    if (!THEME_ID.test(id)) throw new Error(`E_TOKEN_THEME_ID ${id}`)
    const value = (appearance: 'light' | 'dark') => {
      const token = flat.find((t) => t.path === `backdrop.${id}.${appearance}`)
      if (token?.type !== 'gradient') throw new Error(`E_TOKEN_BACKDROP ${id} ${appearance}`)
      return backdropGradient(token)
    }
    return { id, light: value('light'), dark: value('dark') }
  })
}

/** The iPhone's own theme slots (`phone-theme.<id>.light|dark.<slot>`) that stand in for a theme colour. */
export const PHONE_THEME_COLOURS: Readonly<Record<string, string>> = {
  background: 'color.phone.background',
  card: 'color.phone.card',
  separator: 'color.phone.separator',
  'text-secondary': 'color.phone.text-secondary',
  'text-faint': 'color.phone.text-faint',
  'glass-tint': 'color.phone.glass-opaque',
  accent: 'color.accent.fill',
  'accent-mark': 'color.accent.text',
  'on-accent': 'color.accent.on-fill',
}
const PHONE_THEME_GLOW = ['glow-start', 'glow-end']

export interface PhoneTheme {
  id: string
  light: Map<string, ColorValue>
  dark: Map<string, ColorValue>
}

/** Each theme's iPhone slots; a slot or theme Devot does not know is refused. */
export function phoneThemes(tree: TokenTree, known: readonly string[]): PhoneTheme[] {
  const flat = flatten(tree)
  const ids = [...new Set(flat.map((t) => t.path.split('.')[1]!))]
  return ids.map((id) => {
    if (!known.includes(id)) throw new Error(`E_TOKEN_PHONE_THEME ${id}`)
    const slots = (appearance: 'light' | 'dark') =>
      new Map(
        flat
          .filter((t) => t.path.startsWith(`phone-theme.${id}.${appearance}.`))
          .map((t) => {
            const slot = t.path.split('.').at(-1)!
            if (
              t.type !== 'color' ||
              !(slot in PHONE_THEME_COLOURS || PHONE_THEME_GLOW.includes(slot))
            ) {
              throw new Error(`E_TOKEN_PHONE_THEME_SLOT ${t.path}`)
            }
            return [slot, t.value as ColorValue] as const
          }),
      )
    return { id, light: slots('light'), dark: slots('dark') }
  })
}

/** The phone colours a theme's slots replace, as declarations; the accent and its label stay the Mac's on the page. */
function phoneDeclarations(slots: Map<string, ColorValue>): string[] {
  return [...slots]
    .filter(([slot]) => PHONE_THEME_COLOURS[slot]?.startsWith('color.phone.'))
    .map(([slot, colour]) => `  ${cssVarName(PHONE_THEME_COLOURS[slot]!)}: ${cssColor(colour)};`)
}

/**
 * Only theme colours and non-colour base tokens are exported: components never use primitive
 * colours. `themes` follow the default `light`/`dark`, scoped by `data-theme`, with the same tokens;
 * the gradient themes in `backdrops` come after them.
 */
export function compile(
  base: TokenTree,
  light: TokenTree,
  dark: TokenTree,
  themes: readonly ThemeTokens[] = [],
  backdrops: TokenTree = {},
  phoneTree: TokenTree = {},
): CompiledTokens {
  const baseFlat = flatten(base)
  const shared = baseFlat.filter((t) => t.type !== 'color')
  const colours = (tree: TokenTree) =>
    resolve(flatten(tree), baseFlat).filter((t) => t.type === 'color')
  const lightTheme = colours(light)
  const darkTheme = colours(dark)

  const paths = (list: FlatToken[]) =>
    list
      .map((t) => t.path)
      .sort()
      .join()
  if (paths(lightTheme) !== paths(darkTheme)) {
    throw new Error('E_TOKEN_THEMES_DIFFER')
  }
  const builtIn = themes.map((theme) => {
    if (!THEME_ID.test(theme.id)) throw new Error(`E_TOKEN_THEME_ID ${theme.id}`)
    const own = { id: theme.id, light: colours(theme.light), dark: colours(theme.dark) }
    if (paths(own.light) !== paths(lightTheme) || paths(own.dark) !== paths(lightTheme)) {
      throw new Error(`E_TOKEN_THEMES_DIFFER ${theme.id}`)
    }
    return own
  })

  const gradients = backdropThemes(backdrops)
  const phone = phoneThemes(phoneTree, [...themes.map((t) => t.id), ...gradients.map((t) => t.id)])
  const lightDeclarations = lightTheme.map((t) => themeDeclaration(t, 'light'))
  const darkDeclarations = darkTheme.map((t) => themeDeclaration(t, 'dark'))
  const css = [
    `/* ${HEADER} */`,
    ':root {',
    '  color-scheme: light dark;',
    ...shared.map((t) => `  ${cssVarName(t.path)}: ${cssValue(t)};`),
    ...lightDeclarations,
    '}',
    '',
    `@media ${DARK_QUERY} {`,
    `  ${FOLLOWS_SYSTEM} {`,
    ...darkDeclarations.map((d) => `  ${d}`),
    '  }',
    '}',
    '',
    // The appearance chosen in Settings, and a theme card's preview, whatever the system shows.
    `${CHOSEN('dark')} {`,
    '  color-scheme: dark;',
    ...darkDeclarations,
    '}',
    '',
    `${CHOSEN('light')} {`,
    '  color-scheme: light;',
    ...lightDeclarations,
    '}',
    '',
    ...builtIn.flatMap((theme) => [
      `/* The ${theme.id} theme: data-theme='${theme.id}' on the root element. */`,
      // A theme is independent of the system accent: its accent tokens are its own values.
      ...themeRules(
        theme.id,
        theme.light.map((t) => themeDeclaration(t, 'light', false)),
        theme.dark.map((t) => themeDeclaration(t, 'dark', false)),
      ),
    ]),
    ...gradients.flatMap((theme) => {
      const own = phone.find((p) => p.id === theme.id)
      return [
        `/* The ${theme.id} gradient theme: data-theme='${theme.id}' on the root element. */`,
        ...themeRules(
          theme.id,
          [`  --backdrop: ${theme.light};`, ...phoneDeclarations(own?.light ?? new Map())],
          [`  --backdrop: ${theme.dark};`, ...phoneDeclarations(own?.dark ?? new Map())],
        ),
      ]
    }),
  ].join('\n')

  const constants = (list: FlatToken[]) =>
    Object.fromEntries(list.map((t) => [t.path, cssValue(t)]))
  const ts = [
    `// ${HEADER}`,
    '',
    `export const sizes = ${JSON.stringify(constants(shared), null, 2)} as const`,
    '',
    `export const light = ${JSON.stringify(constants(lightTheme), null, 2)} as const`,
    '',
    `export const dark = ${JSON.stringify(constants(darkTheme), null, 2)} as const`,
    '',
    ...builtIn.flatMap((theme) => [
      `export const ${theme.id}Light = ${JSON.stringify(constants(theme.light), null, 2)} as const`,
      '',
      `export const ${theme.id}Dark = ${JSON.stringify(constants(theme.dark), null, 2)} as const`,
      '',
    ]),
    'export type ThemeColor = keyof typeof light',
    '',
    '/** The CSS custom property for a theme colour, for inline styles. */',
    "export const cssVar = (color: ThemeColor) => `var(--${color.replaceAll('.', '-')})`",
    '',
    "/** The iPhone's own theme colours (design/tokens/phone-themes.tokens.json). */",
    `export const phoneThemes = ${JSON.stringify(
      Object.fromEntries(
        phone.map((p) => [
          p.id,
          {
            light: Object.fromEntries([...p.light].map(([k, v]) => [k, cssColor(v)])),
            dark: Object.fromEntries([...p.dark].map(([k, v]) => [k, cssColor(v)])),
          },
        ]),
      ),
      null,
      2,
    )} as const`,
    '',
  ].join('\n')

  return { css, ts }
}

// Compiles DTCG design tokens into CSS custom properties and TS constants; `build.ts` does the file I/O.

export type TokenTree = { [key: string]: TokenTree | Token | unknown }

export interface Token {
  $value: unknown
  $type?: string
  $extensions?: { 'app.devot'?: { source?: string } }
}

interface ColorValue {
  colorSpace: 'srgb'
  components: [number, number, number]
  hex: string
  alpha?: number
}

interface DimensionValue {
  value: number
  unit: 'px' | 'rem'
}

export interface FlatToken {
  path: string
  type: string
  value: unknown
  systemAccent: boolean
}

const isToken = (node: unknown): node is Token =>
  typeof node === 'object' && node !== null && '$value' in node

export function flatten(tree: TokenTree, prefix = '', inheritedType = ''): FlatToken[] {
  const out: FlatToken[] = []
  const groupType = typeof tree['$type'] === 'string' ? (tree['$type'] as string) : inheritedType
  for (const [key, node] of Object.entries(tree)) {
    if (key.startsWith('$')) continue
    const path = prefix ? `${prefix}.${key}` : key
    if (isToken(node)) {
      out.push({
        path,
        type: node.$type ?? groupType,
        value: node.$value,
        systemAccent: node.$extensions?.['app.devot']?.source === 'system-accent',
      })
    } else if (typeof node === 'object' && node !== null) {
      out.push(...flatten(node as TokenTree, path, groupType))
    }
  }
  return out
}

const REFERENCE = /^\{([^}]+)\}$/

export function resolve(tokens: FlatToken[], base: FlatToken[]): FlatToken[] {
  const byPath = new Map([...base, ...tokens].map((t) => [t.path, t]))
  const resolveValue = (value: unknown, seen: Set<string>): unknown => {
    if (typeof value !== 'string') return value
    const match = REFERENCE.exec(value)
    if (!match) return value
    const target = byPath.get(match[1]!)
    if (!target) throw new Error(`E_TOKEN_REFERENCE_MISSING ${match[1]}`)
    if (seen.has(target.path)) throw new Error(`E_TOKEN_REFERENCE_CYCLE ${target.path}`)
    return resolveValue(target.value, new Set([...seen, target.path]))
  }
  return tokens.map((t) => ({ ...t, value: resolveValue(t.value, new Set([t.path])) }))
}

const round = (n: number) => Math.round(n * 1000) / 1000

export function cssValue(token: FlatToken): string {
  switch (token.type) {
    case 'color': {
      const c = token.value as ColorValue
      if (c.alpha === undefined || c.alpha === 1) return c.hex
      const [r, g, b] = c.components.map((x) => Math.round(x * 255))
      return `rgb(${r} ${g} ${b} / ${round(c.alpha)})`
    }
    case 'dimension': {
      const d = token.value as DimensionValue
      return `${d.value}${d.unit}`
    }
    case 'fontFamily': {
      const families = Array.isArray(token.value) ? token.value : [token.value]
      return families
        .map((f) => (/^[a-z-]+$/i.test(String(f)) ? String(f) : `'${String(f)}'`))
        .join(', ')
    }
    case 'duration': {
      const d = token.value as { value: number; unit: 'ms' | 's' }
      return `${d.value}${d.unit}`
    }
    case 'cubicBezier':
      return `cubic-bezier(${(token.value as number[]).join(', ')})`
    case 'fontWeight':
    case 'number':
      return String(token.value)
    default:
      throw new Error(`E_TOKEN_TYPE_UNSUPPORTED ${token.path} ${token.type}`)
  }
}

export const cssVarName = (path: string) => `--${path.replaceAll('.', '-')}`

/**
 * System-accent colours read a runtime variable named after the token's role (`--system-accent-fill-light`
 * for `color.accent.fill`, set in theme/accent.ts) and fall back to the token's own value.
 */
function themeDeclaration(
  token: FlatToken,
  appearance: 'light' | 'dark',
  followsSystemAccent = true,
): string {
  const value = cssValue(token)
  const role = token.path.split('.').at(-1)
  const css =
    token.systemAccent && followsSystemAccent
      ? `var(--system-accent-${role}-${appearance}, ${value})`
      : value
  return `  ${cssVarName(token.path)}: ${css};`
}

export interface CompiledTokens {
  css: string
  ts: string
}

const HEADER = 'Generated by scripts/tokens/build.ts from design/tokens. Do not edit.'

export const DARK_QUERY = '(prefers-color-scheme: dark)'

/** Follows the system unless Settings > Appearance chose one (`data-appearance`, theme/appearance.ts). */
const FOLLOWS_SYSTEM = ":root:not([data-appearance='light'])"

/** The root when Settings chose an appearance, or any element pinned to one (`data-appearance-preview`, the theme cards). */
const CHOSEN = (appearance: 'light' | 'dark') =>
  `:root[data-appearance='${appearance}'], [data-appearance-preview='${appearance}']`

export interface ThemeTokens {
  /** The `data-theme` value on the root (a plain lowercase word). */
  id: string
  light: TokenTree
  dark: TokenTree
}

const THEME_ID = /^[a-z][a-z0-9]*$/

/** The rules of a built-in theme, in the order that makes them win (see `compile`). */
function themeRules(id: string, light: FlatToken[], dark: FlatToken[]): string[] {
  // A theme is independent of the system accent: its accent tokens are its own values.
  const lightDeclarations = light.map((t) => themeDeclaration(t, 'light', false))
  const darkDeclarations = dark.map((t) => themeDeclaration(t, 'dark', false))
  const root = `:root[data-theme='${id}']`
  // A theme's rules are one attribute heavier than the default theme's wherever both could apply,
  // and come after them, so the theme wins in every context. `data-theme-preview` shows the theme
  // in the appearance `data-appearance-preview` names (the Settings theme cards).
  const chosen = (appearance: 'light' | 'dark') =>
    `${root}[data-appearance='${appearance}'], [data-theme-preview='${id}'][data-appearance-preview='${appearance}']`
  return [
    `${root} {`,
    ...lightDeclarations,
    '}',
    '',
    `@media ${DARK_QUERY} {`,
    `  ${root}:not([data-appearance='light']) {`,
    ...darkDeclarations.map((d) => `  ${d}`),
    '  }',
    '}',
    '',
    `${chosen('dark')} {`,
    '  color-scheme: dark;',
    ...darkDeclarations,
    '}',
    '',
    `${chosen('light')} {`,
    '  color-scheme: light;',
    ...lightDeclarations,
    '}',
    '',
  ]
}

/**
 * Only theme colours and non-colour base tokens are exported: components never use primitive
 * colours. `themes` follow the default `light`/`dark`, scoped by `data-theme`, with the same tokens.
 */
export function compile(
  base: TokenTree,
  light: TokenTree,
  dark: TokenTree,
  themes: readonly ThemeTokens[] = [],
): CompiledTokens {
  const baseFlat = flatten(base)
  const shared = baseFlat.filter((t) => t.type !== 'color')
  const colours = (tree: TokenTree) =>
    resolve(flatten(tree), baseFlat).filter((t) => t.type === 'color')
  const lightTheme = colours(light)
  const darkTheme = colours(dark)

  const paths = (list: FlatToken[]) =>
    list
      .map((t) => t.path)
      .sort()
      .join()
  if (paths(lightTheme) !== paths(darkTheme)) {
    throw new Error('E_TOKEN_THEMES_DIFFER')
  }
  const builtIn = themes.map((theme) => {
    if (!THEME_ID.test(theme.id)) throw new Error(`E_TOKEN_THEME_ID ${theme.id}`)
    const own = { id: theme.id, light: colours(theme.light), dark: colours(theme.dark) }
    if (paths(own.light) !== paths(lightTheme) || paths(own.dark) !== paths(lightTheme)) {
      throw new Error(`E_TOKEN_THEMES_DIFFER ${theme.id}`)
    }
    return own
  })

  const lightDeclarations = lightTheme.map((t) => themeDeclaration(t, 'light'))
  const darkDeclarations = darkTheme.map((t) => themeDeclaration(t, 'dark'))
  const css = [
    `/* ${HEADER} */`,
    ':root {',
    '  color-scheme: light dark;',
    ...shared.map((t) => `  ${cssVarName(t.path)}: ${cssValue(t)};`),
    ...lightDeclarations,
    '}',
    '',
    `@media ${DARK_QUERY} {`,
    `  ${FOLLOWS_SYSTEM} {`,
    ...darkDeclarations.map((d) => `  ${d}`),
    '  }',
    '}',
    '',
    // The appearance chosen in Settings, and a theme card's preview, whatever the system shows.
    `${CHOSEN('dark')} {`,
    '  color-scheme: dark;',
    ...darkDeclarations,
    '}',
    '',
    `${CHOSEN('light')} {`,
    '  color-scheme: light;',
    ...lightDeclarations,
    '}',
    '',
    ...builtIn.flatMap((theme) => [
      `/* The ${theme.id} theme: data-theme='${theme.id}' on the root element. */`,
      ...themeRules(theme.id, theme.light, theme.dark),
    ]),
  ].join('\n')

  const constants = (list: FlatToken[]) =>
    Object.fromEntries(list.map((t) => [t.path, cssValue(t)]))
  const ts = [
    `// ${HEADER}`,
    '',
    `export const sizes = ${JSON.stringify(constants(shared), null, 2)} as const`,
    '',
    `export const light = ${JSON.stringify(constants(lightTheme), null, 2)} as const`,
    '',
    `export const dark = ${JSON.stringify(constants(darkTheme), null, 2)} as const`,
    '',
    ...builtIn.flatMap((theme) => [
      `export const ${theme.id}Light = ${JSON.stringify(constants(theme.light), null, 2)} as const`,
      '',
      `export const ${theme.id}Dark = ${JSON.stringify(constants(theme.dark), null, 2)} as const`,
      '',
    ]),
    'export type ThemeColor = keyof typeof light',
    '',
    '/** The CSS custom property for a theme colour, for inline styles. */',
    "export const cssVar = (color: ThemeColor) => `var(--${color.replaceAll('.', '-')})`",
    '',
  ].join('\n')

  return { css, ts }
}

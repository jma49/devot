// Writes Strings.swift and Localizable.xcstrings for the iPhone's native screens from the English
// catalog and its translations, in the iPhone's wording, the Share Extension's own pair from the `share` area, and SettingsIndex.swift from Settings' search entries. `--check` fails instead of writing when they are stale (CI runs it).
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { camelCase, escapeKeyword } from '../tokens/swift.ts'

const GENERATED = 'src-tauri/apple/DevotScreens/Sources/DevotScreens/Generated'
export const STRINGS_SWIFT = `${GENERATED}/Strings.swift`
export const XCSTRINGS = `${GENERATED}/Localizable.xcstrings`
export const SETTINGS_INDEX = `${GENERATED}/SettingsIndex.swift`

const SHARE_GENERATED = 'src-tauri/apple/DevotShare/Sources/DevotShare/Generated'
export const SHARE_STRINGS_SWIFT = `${SHARE_GENERATED}/Strings.swift`
export const SHARE_XCSTRINGS = `${SHARE_GENERATED}/Localizable.xcstrings`
/** The Share Extension carries only its own area, so it stays small. */
const SHARE_PREFIX = 'share.'
export const APP_INTENTS_XCSTRINGS = 'src-tauri/gen/apple/devot_Intents/Localizable.xcstrings'
const INTENT_PREFIX = 'intent.'

const CATALOG = 'src/renderer/src/i18n/en'
/** Each translation's catalog folder and iPhone wording, by its string catalog language. */
const TRANSLATIONS = {
  'zh-Hans': {
    dir: 'src/renderer/src/i18n/zh-Hans',
    wording: 'src/renderer/src/i18n/zh-Hans/phoneWording.ts',
    name: 'zhHansPhone',
  },
}
const PANES_MODULE = 'src/renderer/src/settings/panes.ts'
const ENTRIES_MODULE = 'src/renderer/src/settings/searchEntries.ts'
const IPHONE_WORDING = 'src/renderer/src/i18n/phone.ts'

const HEADER = '// Generated by scripts/i18n/apple.ts from src/renderer/src/i18n. Do not edit.'

type Catalog = Readonly<Record<string, string>>

/** The page's `{name}` placeholders, each once, in order; `{{name}}` is a template field, not one. */
function placeholders(text: string): string[] {
  return [...new Set([...text.matchAll(/(?<!\{)\{(\w+)\}(?!\})/g)].map((match) => match[1]!))]
}

const SWIFT_ESCAPES: Record<string, string> = {
  '\\': '\\\\',
  '"': '\\"',
  '\n': '\\n',
  '\r': '\\r',
  '\t': '\\t',
}

function swiftString(text: string): string {
  const escaped = [...text].map((char) => {
    const code = char.codePointAt(0)!
    return SWIFT_ESCAPES[char] ?? (code < 0x20 ? `\\u{${code.toString(16)}}` : char)
  })
  return `"${escaped.join('')}"`
}

const SWIFT_HELPERS = `  static func text(_ key: String, _ english: String) -> String {
    catalog.localizedString(forKey: key, value: english, table: nil)
  }

  /// Each \`{name}\` that has a value replaced in one pass, as the page's \`format\` does: an inserted
  /// value is never read again, so braces or dollar signs in it show as typed.
  static func fill(_ template: String, _ values: [String: String]) -> String {
    var out = ""
    var rest = template[...]
    while let open = rest.firstIndex(of: "{") {
      out += rest[..<open]
      let afterOpen = rest.index(after: open)
      if let close = rest[afterOpen...].firstIndex(of: "}") {
        let name = String(rest[afterOpen..<close])
        let isWord = !name.isEmpty
          && name.allSatisfy { $0.isASCII && ($0.isLetter || $0.isNumber || $0 == "_") }
        if isWord, let value = values[name] {
          out += value
          rest = rest[rest.index(after: close)...]
          continue
        }
      }
      out += "{"
      rest = rest[afterOpen...]
    }
    return out + rest
  }
`

/** Xcode's own layout for a string catalog, so opening it in Xcode changes nothing. */
function xcodeJson(value: unknown): string {
  return JSON.stringify(value, null, 2).replace(/^(\s*"(?:[^"\\]|\\.)*"): /gm, '$1 : ') + '\n'
}

/**
 * `L10n`, one static function per key that takes its placeholders as labelled `String`
 * arguments, and the string catalog it reads. `wording` replaces a message's text, as the
 * page's iPhone layout does, and may use only the message's own placeholders.
 */
export function compileStrings(
  messages: Catalog,
  wording: Partial<Catalog>,
  translations: Readonly<Record<string, Partial<Catalog>>> = {},
  enumName = 'L10n',
): { swift: string; xcstrings: string } {
  const seen = new Set(['text', 'fill'])
  const functions: string[] = []
  const strings: Record<string, unknown> = {}
  for (const [key, english] of Object.entries(messages)) {
    const name = escapeKeyword(camelCase(key.split('.'), 'key'))
    if (seen.has(name)) throw new Error(`E_I18N_SWIFT_NAME ${key}`)
    seen.add(name)
    const args = placeholders(english)
    if (args.some((arg) => !/^[A-Za-z_]/.test(arg))) {
      throw new Error(`E_I18N_PLACEHOLDER_NAME ${key}`)
    }
    const text = wording[key] ?? english
    if (placeholders(text).some((placeholder) => !args.includes(placeholder))) {
      throw new Error(`E_I18N_PLACEHOLDERS ${key}`)
    }
    const lookup = `text(${swiftString(key)}, ${swiftString(text)})`
    const params = args.map((arg, i) => `${escapeKeyword(arg)} p${i}: String`).join(', ')
    const body =
      args.length === 0
        ? lookup
        : `fill(${lookup}, [${args.map((arg, i) => `${swiftString(arg)}: p${i}`).join(', ')}])`
    functions.push(`  public static func ${name}(${params}) -> String {\n    ${body}\n  }\n`)
    const localizations: Record<string, unknown> = {
      en: { stringUnit: { state: 'translated', value: text } },
    }
    for (const [language, catalog] of Object.entries(translations)) {
      const translated = catalog[key]
      if (translated === undefined) continue
      if (placeholders(translated).some((placeholder) => !args.includes(placeholder))) {
        throw new Error(`E_I18N_PLACEHOLDERS ${language} ${key}`)
      }
      localizations[language] = { stringUnit: { state: 'translated', value: translated } }
    }
    strings[key] = { extractionState: 'manual', localizations }
  }

  const swift = [
    HEADER,
    '',
    'import Foundation',
    '',
    '#if SWIFT_PACKAGE',
    'private let catalog = Bundle.module',
    '#else',
    'private final class CatalogAnchor {}',
    'private let catalog = Bundle(for: CatalogAnchor.self)',
    '#endif',
    '',
    `public enum ${enumName} {`,
    ...functions,
    SWIFT_HELPERS + '}',
    '',
  ].join('\n')
  const sorted = Object.fromEntries(
    Object.keys(strings)
      .sort()
      .map((key) => [key, strings[key]]),
  )
  const xcstrings = xcodeJson({ sourceLanguage: 'en', strings: sorted, version: '1.0' })
  return { swift, xcstrings }
}

interface IndexEntry {
  readonly pane: string
  readonly label: string
  readonly only?: 'mac' | 'phone'
}

/**
 * `SettingsIndex`, what the native Settings' search looks through: the panes in navigation order
 * with their label keys, then each entry of `searchEntries.ts`. Labels stay keys, which the
 * string catalog resolves, so the search reads the same words the rows show.
 */
export function compileSettingsIndex(
  entries: readonly IndexEntry[],
  panes: readonly string[],
  tabs: Readonly<Record<string, { readonly label: string }>>,
): string {
  const device = (only: IndexEntry['only']) => (only ? `.${only}` : 'nil')
  return [
    '// Generated by scripts/i18n/apple.ts from src/renderer/src/settings. Do not edit.',
    '',
    'enum SettingsIndex {',
    '  enum Device { case mac, phone }',
    '',
    '  struct Entry: Equatable {',
    '    let pane: String',
    '    let label: String',
    '    let only: Device?',
    '  }',
    '',
    '  static let panes: [(id: String, label: String)] = [',
    ...panes.map((pane) => `    (${swiftString(pane)}, ${swiftString(tabs[pane]!.label)}),`),
    '  ]',
    '',
    '  static let entries: [Entry] = [',
    ...entries.map(
      (entry) =>
        `    Entry(pane: ${swiftString(entry.pane)}, label: ${swiftString(entry.label)}, only: ${device(entry.only)}),`,
    ),
    '  ]',
    '}',
    '',
  ].join('\n')
}

/** The English catalog's area modules, read straight from `root` (the folder of `index.ts`). */
async function loadAreas(dir: string): Promise<Record<string, string>> {
  const areas = readdirSync(dir)
    .filter((file) => file.endsWith('.ts') && file !== 'index.ts' && !file.endsWith('.test.ts'))
    .sort()
  const messages: Record<string, string> = {}
  for (const area of areas) {
    Object.assign(messages, (await import(pathToFileURL(join(dir, area)).href)).messages)
  }
  return messages
}

async function loadCatalog(root: string): Promise<{
  messages: Catalog
  wording: Partial<Catalog>
  translations: Record<string, Partial<Catalog>>
}> {
  const messages = await loadAreas(join(root, CATALOG))
  const { enPhone } = await import(pathToFileURL(join(root, IPHONE_WORDING)).href)
  const translations: Record<string, Partial<Catalog>> = {}
  for (const [language, source] of Object.entries(TRANSLATIONS)) {
    const translated = await loadAreas(join(root, source.dir))
    const phone = (await import(pathToFileURL(join(root, source.wording)).href))[source.name]
    translations[language] = { ...translated, ...phone }
  }
  return { messages, wording: enPhone, translations }
}

export async function appleStrings(root: string): Promise<[string, string][]> {
  const { messages, wording, translations } = await loadCatalog(root)
  const { swift, xcstrings } = compileStrings(messages, wording, translations)
  const share = compileStrings(
    Object.fromEntries(Object.entries(messages).filter(([key]) => key.startsWith(SHARE_PREFIX))),
    wording,
    translations,
    'ShareL10n',
  )
  const intents = compileStrings(
    Object.fromEntries(Object.entries(messages).filter(([key]) => key.startsWith(INTENT_PREFIX))),
    {},
    translations,
    'IntentL10n',
  )
  const { PANES, PANE_TABS } = await import(pathToFileURL(join(root, PANES_MODULE)).href)
  const { SETTINGS_ENTRIES } = await import(pathToFileURL(join(root, ENTRIES_MODULE)).href)
  return [
    [STRINGS_SWIFT, swift],
    [XCSTRINGS, xcstrings],
    [SETTINGS_INDEX, compileSettingsIndex(SETTINGS_ENTRIES, PANES, PANE_TABS)],
    [SHARE_STRINGS_SWIFT, share.swift],
    [SHARE_XCSTRINGS, share.xcstrings],
    [APP_INTENTS_XCSTRINGS, intents.xcstrings],
  ]
}

export function staleOutputs(
  root: string,
  outputs: readonly (readonly [string, string])[],
): string[] {
  return outputs
    .filter(([path, content]) => {
      try {
        return readFileSync(join(root, path), 'utf8') !== content
      } catch {
        return true
      }
    })
    .map(([path]) => path)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = join(import.meta.dirname, '../..')
  const outputs = await appleStrings(root)
  if (process.argv.includes('--check')) {
    const stale = staleOutputs(root, outputs)
    if (stale.length > 0) {
      console.error(`E_STRINGS_STALE ${stale.join(' ')}: run pnpm i18n:apple`)
      process.exit(1)
    }
  } else {
    for (const [path, content] of outputs) {
      mkdirSync(dirname(join(root, path)), { recursive: true })
      writeFileSync(join(root, path), content)
    }
  }
}

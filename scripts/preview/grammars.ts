// Generates src/core/preview/grammars.ts: a lazy loader for every highlight.js
// grammar, plus the alias table, so a code block loads only its own grammar.
// Run `pnpm grammars` after upgrading highlight.js; a test fails when stale.
import hljs from 'highlight.js'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const GRAMMARS_PATH = 'src/core/preview/grammars.ts'

export function grammarsSource(): string {
  const names = hljs.listLanguages().sort()
  const aliases: [string, string][] = []
  for (const name of names) {
    for (const alias of hljs.getLanguage(name)?.aliases ?? []) {
      const key = alias.toLowerCase()
      if (key !== name && !names.includes(key) && !aliases.some(([a]) => a === key)) {
        aliases.push([key, name])
      }
    }
  }
  aliases.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  const quote = (s: string) => JSON.stringify(s)
  const lines = [
    '// Generated by scripts/preview/grammars.ts from highlight.js. Do not edit;',
    '// run `pnpm grammars` after upgrading highlight.js.',
    "import type { LanguageFn } from 'highlight.js'",
    '',
    'export type GrammarLoader = () => Promise<{ default: LanguageFn }>',
    '',
    '/** Every highlight.js grammar, loaded on first use. */',
    'export const GRAMMARS: Readonly<Record<string, GrammarLoader>> = {',
    ...names.map(
      (n) => `  ${quote(n)}: () => import(${quote(`highlight.js/lib/languages/${n}`)}),`,
    ),
    '}',
    '',
    '/** Other names of those grammars, lower-cased. */',
    'export const GRAMMAR_ALIASES: Readonly<Record<string, string>> = {',
    ...aliases.map(([a, n]) => `  ${quote(a)}: ${quote(n)},`),
    '}',
    '',
  ]
  return lines.join('\n')
}

if (process.argv[1]?.endsWith('grammars.ts')) {
  writeFileSync(join(process.cwd(), GRAMMARS_PATH), grammarsSource())
}
